#!/usr/bin/env python3
"""make_data.py STOCK_EXE NITROUS_EXE OUT.h
Reads the nosebleed camera preset ("Nosebleeds" camera record 7E35D4F7: two parameter tables at VA 0x1028AB8 and 0x1028BB8,
0xA8 bytes each) from a stock nba2k14.exe and from the Nitrous nba2k14.exe, and writes them as C arrays.
Also reports every other byte that differs between the two exes (they are NOT part of the nosebleed camera)."""
import struct, sys
stock = open(sys.argv[1], 'rb').read(); nitro = open(sys.argv[2], 'rb').read()
pe = struct.unpack_from('<I', stock, 0x3c)[0]; ns = struct.unpack_from('<H', stock, pe + 6)[0]
so = pe + 24 + struct.unpack_from('<H', stock, pe + 20)[0]; ib = struct.unpack_from('<I', stock, pe + 52)[0]
secs = [(struct.unpack_from('<I', stock, so + 40*i + 12)[0] + ib, struct.unpack_from('<I', stock, so + 40*i + 8)[0],
         struct.unpack_from('<I', stock, so + 40*i + 20)[0]) for i in range(ns)]
def off(va):
    for v, rs, ra in secs:
        if v <= va < v + rs: return ra + va - v
TABLES = (('A', 0x1028AB8), ('B', 0x1028BB8)); LEN = 0xA8
out = ['/* generated by tools/make_data.py - the nosebleed camera preset ("Nosebleeds", record 7E35D4F7) of stock and Nitrous nba2k14.exe */',
       '#define NB_LEN %d' % LEN]
for name, va in TABLES:
    for tag, d in (('stock', stock), ('nitro', nitro)):
        o = off(va); b = d[o:o + LEN]
        out.append('static const unsigned char nb_%s_%s[NB_LEN] = {' % (tag, name))
        for i in range(0, LEN, 16): out.append('    ' + ','.join('0x%02X' % x for x in b[i:i+16]) + ',')
        out.append('};')
    out.append('#define NB_VA_%s 0x%08XU' % (name, va))
open(sys.argv[3], 'w').write('\n'.join(out) + '\n')
# report
diff = [i for i in range(len(stock)) if stock[i] != nitro[i]]
inside = [i for i in diff if any(off(va) <= i < off(va) + LEN for _, va in TABLES)]
print('bytes that differ between the two exes: %d, of which in the nosebleed camera tables: %d' % (len(diff), len(inside)))
